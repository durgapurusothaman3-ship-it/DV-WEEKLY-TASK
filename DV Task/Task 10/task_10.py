import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn  as sns

df=pd.read_csv("/content/drive/MyDrive/PROJECT/kc_house_data_processed.csv")

df.head()

df.tail()

df.info()

df.isnull()

df.describe()

df['date'] = pd.to_datetime(
    df['date'],
    format='%Y%m%dT%H%M%S',
    errors='coerce'
)

cols = [
    'price', 'sqft_living', 'grade',
    'waterfront', 'lat', 'long'
]

for col in cols:
    df[col] = pd.to_numeric(df[col], errors='coerce')

df = df.dropna(subset=cols)

df = df[
    (df['price'] > 0) &
    (df['sqft_living'] > 0)
].copy()

print("Data preparation completed!")
display(df.head())

plt.figure(figsize=(9, 5))

sns.regplot(
    data=df,
    x='sqft_living',
    y='price',
    scatter_kws={'alpha': 0.3},
    line_kws={'color': 'red'}
)

plt.title('Living Area vs House Price')
plt.xlabel('Living Area (Square Feet)')
plt.ylabel('House Price')
plt.show()

plt.figure(figsize=(10, 5))

sns.boxplot(
    data=df,
    x='grade',
    y='price'
)

plt.title('House Price Distribution by Property Grade')
plt.xlabel('Property Grade')
plt.ylabel('House Price')
plt.show()

df['waterfront_status'] = df['waterfront'].map({
    0: 'No Waterfront',
    1: 'Waterfront'
})

plt.figure(figsize=(8, 5))

sns.boxplot(
    data=df,
    x='waterfront_status',
    y='price'
)

plt.title('House Price by Waterfront Status')
plt.xlabel('Waterfront Status')
plt.ylabel('House Price')
plt.show()

plt.figure(figsize=(10, 7))

scatter = plt.scatter(
    df['long'],
    df['lat'],
    c=df['price'],
    cmap='viridis',
    s=10,
    alpha=0.6
)

plt.colorbar(
    scatter,
    label='House Price'
)

plt.title('Geographic House Price Heatmap')
plt.xlabel('Longitude')
plt.ylabel('Latitude')

plt.show()

print("Real Estate Investment Summary Report")
print(df.groupby('zipcode')['price'].median().nlargest(5))





