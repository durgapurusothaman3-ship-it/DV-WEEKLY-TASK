df["date"] = pd.to_datetime(
    df["date"],
    format="%Y%m%dT%H%M%S",
    errors="coerce"
)

df["sale_year"] = df["date"].dt.year

df["property_age"] = df["sale_year"] - df["yr_built"]

df.loc[df["property_age"] < 0, "property_age"] = np.nan

df["is_renovated"] = (
    df["yr_renovated"].fillna(0) > 0
).astype(int)

df["years_since_renovation"] = np.where(
    (df["is_renovated"] == 1) &
    (df["yr_renovated"] <= df["sale_year"]),
    df["sale_year"] - df["yr_renovated"],
    np.nan
)

print("Temporal attributes created successfully!")

display(
    df[[
        "date", "sale_year", "yr_built",
        "property_age", "yr_renovated",
        "is_renovated", "years_since_renovation"
    ]].head(10)
)

df["price_per_sqft_living"] = (
    df["price"] / df["sqft_living"]
)

df["price_per_sqft_lot"] = (
    df["price"] / df["sqft_lot"]
)

print("Price per square foot calculated successfully!")

display(
    df[[
        "price", "sqft_living", "sqft_lot",
        "price_per_sqft_living",
        "price_per_sqft_lot"
    ]].head(10)
)

plt.figure(figsize=(8, 5))
sns.boxplot(y=df['price'])
plt.title('Outlier Analysis of Property Prices')
plt.ylabel('Price')
plt.show()

Q1 = df['price'].quantile(0.25)
Q3 = df['price'].quantile(0.75)
IQR = Q3 - Q1

lower = Q1 - 1.5 * IQR
upper = Q3 + 1.5 * IQR

outliers = df[(df['price'] < lower) | (df['price'] > upper)]

print("Number of Outliers:", len(outliers))
print(outliers[['price']].head(10))